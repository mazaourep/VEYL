#!/usr/bin/env python3
"""Build dist/VEYL.lua: every module from loader.lua's MODULES list in one file.

Use it when the runtime cannot fetch over HTTP or has no loadstring
(for example a plain LocalScript). Run from the repository root:
    python3 tools/bundle.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def module_list():
    loader = (ROOT / "loader.lua").read_text(encoding="utf-8")
    block = re.search(r"local MODULES = \{(.*?)\n\}", loader, re.S)
    if not block:
        sys.exit("MODULES list not found in loader.lua")
    return re.findall(r'"(src/[^"]+\.lua)"', block.group(1))


def main():
    paths = module_list()
    out = [
        "--[[",
        "    VEYL Control — single-file build (generated by tools/bundle.py; do not edit).",
        "    Edit the files in src/ and rebuild. Prefer loader.lua when HttpGet and loadstring exist.",
        "    This file also runs as a LocalScript in StarterPlayer > StarterPlayerScripts.",
        "]]",
        "",
        "local MODULES = {}",
    ]
    for path in paths:
        body = (ROOT / path).read_text(encoding="utf-8").rstrip("\n")
        if not body.startswith("-- VEYL module: "):
            sys.exit(f"{path} is missing the module marker")
        out.append(f'MODULES[#MODULES + 1] = {{ path = "{path}", factory = (function()')
        out.append(body)
        out.append("end)() }")
    out += [
        "",
        "local V = {}",
        "for _, module in ipairs(MODULES) do",
        "    local ok, err = pcall(module.factory, V)",
        "    if not ok then",
        '        warn("[VEYL] Module " .. module.path .. " failed while starting: " .. tostring(err))',
        "        if V.App and V.App.shutdown and V.Session and V.Session.alive then",
        '            pcall(V.App.shutdown, "load failure")',
        "        elseif V.Root then",
        "            if V.Session then",
        "                V.Session.alive = false",
        "            end",
        "            pcall(function()",
        "                V.Root:clean()",
        "            end)",
        "        end",
        "        return",
        "    end",
        "end",
    ]
    target = ROOT / "dist" / "VEYL.lua"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {target.relative_to(ROOT)} ({len(paths)} modules)")


if __name__ == "__main__":
    main()
